#!/usr/bin/env Rscript
# All records in these tests are fabricated; no study extracts are read.
args <- commandArgs(FALSE)
self <- gsub('~+~',' ',sub('^--file=','',args[grepl('^--file=',args)][1]),fixed=TRUE)
project <- dirname(dirname(normalizePath(self,mustWork=TRUE)))
files <- list.files(project,pattern='[.]R$',recursive=TRUE,full.names=FALSE)
files <- file.path(project,files[!grepl('^(work|outputs|release)/',files)])
if(!length(files))stop('No R source files found for syntax checks.')
for(file in files)parse(file)
suppressPackageStartupMessages(library(data.table))
for(file in c('pipeline.R','import_helpers.R','eligibility_pregnancy.R','table1.R','manuscript_tables.R','share_checks.R'))source(file.path(project,'R',file))
checks <- 0L
check <- function(label,passed){if(!isTRUE(passed))stop(label);checks <<- checks+1L}
fails <- function(expr)inherits(tryCatch(force(expr),error=function(e)e),'error')
steps <- pipeline_steps()
check('Every module exists',all(file.exists(file.path(project,steps$script))))
check('Module numbers are unique and ordered',identical(as.integer(steps$number),seq_len(nrow(steps)) ))
check('Leap-day birthday uses February 28',identical(add_calendar_years(as.Date('2020-02-29'),1L),as.Date('2021-02-28')))
check('Nonintegral identifiers fail',fails(canonical_id(c(1,2.5))))
check('Decimal half-up rounding',identical(format_number(320.5,0),'321'))
D<-as.Date;start<-D('2020-01-01')
cohort<-data.table(patient_id=c('synthetic1','synthetic2'),entry=start,dob=D('1990-01-01'),arvstartTHERAP=start-c(179,180),followup_end=start+c(5,100),administrative_exit=start+100,event_date=c(start+5,D(NA)))
episodes<-data.table(patient_id=c('synthetic1','synthetic2','synthetic2','synthetic2'),documented_pregnancy_order=c(1L,1L,2L,3L),analysis_start=start+c(10,0,100,101),analysis_end=start+c(20,10,120,130))
baseline<-data.table(patient_id=c('synthetic1','synthetic2'),who_value=c(NA,3),cd4_value=c(199,500),bmi_value=c(18.5,25),marital_value=c(NA,1),tpt_before_entry=c(0L,1L))
time<-data.table(patient_id=c('synthetic1','synthetic2'),days=c(6L,101L))
c<-table1_population(cohort,episodes,baseline,time,design='cohort')
s<-table1_population(cohort,episodes,baseline,time,design='sccs')
check('Cohort stops before a later pregnancy',c$pregnancy_count[1]==0L)
check('SCCS retains pregnancy after the event',s$pregnancy_count[1]==1L)
check('Pregnancy starting on the final day contributes',c$pregnancy_count[2]==2L)
check('Third pregnancy is excluded',max(s$pregnancy_count)==2L)
check('ART threshold at 180 days',identical(c$art_duration_at_entry,c('<6 months','6–11 months')))
check('Missing baseline values remain explicit',c$who_category[1]=='Missing')
check('Follow-up uses retained days',identical(c$retained_analysis_years,c(6,101)/365.25))
stat<-table1_statistic(c('Yes','No','No'),data.table(type='category',level='Yes',digits=1L))
check('Small counts remain exact',stat$count==1L&&stat$display=='1 (33.3%)')
c[,primary_analysis_tb:=0L];s[,primary_analysis_tb:=1L]
formatted<-table1_formatted(build_table1_statistics(c,s))
check('Headings calculate population size',formatted$cohort[1]=='Full cohort (N = 2)'&&formatted$primary_sccs[1]=='Primary SCCS (N = 2)')
# Test sharing checks with temporary files.
scratch<-tempfile('share_check_');dir.create(scratch)
tryCatch({
  writeLines(c('README.md','share-files.txt'),file.path(scratch,'share-files.txt'))
  writeLines('Example code project.',file.path(scratch,'README.md'))
  check('Reviewed text files pass',length(check_share(scratch))==2L)
  writeLines('fabricated',file.path(scratch,'unreviewed.csv'))
  check('Unreviewed data file fails',fails(check_share(scratch)))
  unlink(file.path(scratch,'unreviewed.csv'))
  writeLines(paste(c('','home','example','private.txt'),collapse='/'),file.path(scratch,'README.md'))
  check('Personal filesystem path fails',fails(check_share(scratch)))
  writeLines(paste0('Google','Drive-','example'),file.path(scratch,'README.md'))
  check('Cloud account location fails',fails(check_share(scratch)))
  writeLines(paste0('gh','p_',paste(rep('x',30),collapse='')),file.path(scratch,'README.md'))
  check('Credential-shaped string fails',fails(check_share(scratch)))
  if(nzchar(Sys.which('git'))) {
    system2('git',c('-C',shQuote(scratch),'init','--quiet'),stdout=FALSE,stderr=FALSE)
    system2('git',c('-C',shQuote(scratch),'add','README.md','share-files.txt'))
    writeLines('Example code project.',file.path(scratch,'README.md'))
    check('Staged sensitive content fails after working copy cleanup',fails(check_share(scratch)))
  }
},finally=unlink(scratch,recursive=TRUE))
message('Parsed ',length(files),' R files; ',checks,' synthetic checks passed.')
